-- Result storage for the exif index type. Written inside the same
-- transaction as CompleteIndexQueue('exif', ...).

-- name: UpsertIndexExifResult :exec
INSERT INTO index_exif_result (
    file_id, image_type,
    camera_make, camera_model, camera_serial, lens_make, lens_model,
    taken_at,
    iso, f_number, exposure_time, focal_length, focal_length_35mm,
    exposure_program, metering_mode, flash,
    orientation, image_width, image_height,
    gps_latitude, gps_longitude, gps_altitude, gps_at,
    software, artist, copyright, image_description,
    xmp_title, xmp_description, xmp_creator, xmp_label, xmp_rating, xmp_keywords, xmp_create_date,
    has_exif, has_xmp
) VALUES (
    sqlc.arg(file_id), sqlc.arg(image_type),
    sqlc.arg(camera_make), sqlc.arg(camera_model), sqlc.arg(camera_serial), sqlc.arg(lens_make), sqlc.arg(lens_model),
    sqlc.arg(taken_at),
    sqlc.arg(iso), sqlc.arg(f_number), sqlc.arg(exposure_time), sqlc.arg(focal_length), sqlc.arg(focal_length_35mm),
    sqlc.arg(exposure_program), sqlc.arg(metering_mode), sqlc.arg(flash),
    sqlc.arg(orientation), sqlc.arg(image_width), sqlc.arg(image_height),
    sqlc.arg(gps_latitude), sqlc.arg(gps_longitude), sqlc.arg(gps_altitude), sqlc.arg(gps_at),
    sqlc.arg(software), sqlc.arg(artist), sqlc.arg(copyright), sqlc.arg(image_description),
    sqlc.arg(xmp_title), sqlc.arg(xmp_description), sqlc.arg(xmp_creator), sqlc.arg(xmp_label), sqlc.arg(xmp_rating), sqlc.arg(xmp_keywords), sqlc.arg(xmp_create_date),
    sqlc.arg(has_exif), sqlc.arg(has_xmp)
)
ON CONFLICT (file_id) DO UPDATE
    SET image_type          = EXCLUDED.image_type,
        camera_make         = EXCLUDED.camera_make,
        camera_model        = EXCLUDED.camera_model,
        camera_serial       = EXCLUDED.camera_serial,
        lens_make           = EXCLUDED.lens_make,
        lens_model          = EXCLUDED.lens_model,
        taken_at            = EXCLUDED.taken_at,
        iso                 = EXCLUDED.iso,
        f_number            = EXCLUDED.f_number,
        exposure_time       = EXCLUDED.exposure_time,
        focal_length        = EXCLUDED.focal_length,
        focal_length_35mm   = EXCLUDED.focal_length_35mm,
        exposure_program    = EXCLUDED.exposure_program,
        metering_mode       = EXCLUDED.metering_mode,
        flash               = EXCLUDED.flash,
        orientation         = EXCLUDED.orientation,
        image_width         = EXCLUDED.image_width,
        image_height        = EXCLUDED.image_height,
        gps_latitude        = EXCLUDED.gps_latitude,
        gps_longitude       = EXCLUDED.gps_longitude,
        gps_altitude        = EXCLUDED.gps_altitude,
        gps_at              = EXCLUDED.gps_at,
        software            = EXCLUDED.software,
        artist              = EXCLUDED.artist,
        copyright           = EXCLUDED.copyright,
        image_description   = EXCLUDED.image_description,
        xmp_title           = EXCLUDED.xmp_title,
        xmp_description     = EXCLUDED.xmp_description,
        xmp_creator         = EXCLUDED.xmp_creator,
        xmp_label           = EXCLUDED.xmp_label,
        xmp_rating          = EXCLUDED.xmp_rating,
        xmp_keywords        = EXCLUDED.xmp_keywords,
        xmp_create_date     = EXCLUDED.xmp_create_date,
        has_exif            = EXCLUDED.has_exif,
